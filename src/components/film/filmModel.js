export const allShots = (project) =>
  project.scenes.flatMap((scene, sceneIndex) =>
    scene.shots.map((shot, index) => ({
      ...shot,
      scene,
      sceneIndex,
      index,
      number: `${sceneIndex + 1}.${index + 1}`,
    })),
  );
export const coverage = (scene) => {
  const shots = scene.shots || [];
  return [
    {
      title: "Establish the place",
      test: /wide|establishing/i,
      field: "size",
      template: TEMPLATES[9],
    },
    {
      title: "Get close to the subject",
      test: /close-up/i,
      field: "size",
      template: TEMPLATES[7],
    },
    {
      title: "Capture a detail or cutaway",
      test: /insert|detail|cutaway/i,
      field: "size",
      template: TEMPLATES[10],
    },
  ].filter(
    (item) => !shots.some((shot) => item.test.test(shot[item.field] || "")),
  );
};
export const reorder = (items, from, to) => {
  const next = [...items];
  const [item] = next.splice(from, 1);
  next.splice(to, 0, item);
  return next;
};
